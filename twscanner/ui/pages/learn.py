def _income_chart():
    c = colors()
    steps = [("營收", 100, "absolute"), ("營業成本", -60, "relative"), ("毛利", 0, "total"),
             ("營業費用", -15, "relative"), ("營業利益（本業）", 0, "total"), ("業外收支", 2, "relative"),
             ("所得稅", -5, "relative"), ("稅後淨利", 0, "total")]
    fig = go.Figure(go.Waterfall(
        x=[s[0] for s in steps], y=[s[1] for s in steps], measure=[s[2] for s in steps],
        increasing=dict(marker=dict(color=c["up"])), decreasing=dict(marker=dict(color=c["down"])),
        totals=dict(marker=dict(color="#94A3B8")), connector=dict(line=dict(color="#CBD5E1", width=1)),
        text=["100", "−60", "40", "−15", "25", "+2", "−5", "22"], textposition="outside"))
    fig.update_layout(height=300, margin=dict(l=8, r=8, t=36, b=8), plot_bgcolor="#FFFFFF",
                      paper_bgcolor="#FFFFFF", showlegend=False, yaxis=dict(visible=False),
                      title=dict(text="每賣 100 元，最後剩多少：一家公司的損益表（示意）", font=dict(size=14)),
                      font=dict(family="Inter, Noto Sans TC, sans-serif", size=12))
    plot(fig)


