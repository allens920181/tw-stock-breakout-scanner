def _stocks():
    st.markdown("## 股票與交易")
    _lesson("K 線", "一根 K 線記錄一天的開盤、最高、最低、收盤。收盤比開盤高是紅 K（漲），反之是綠 K（跌）。"
            "上下的細線（影線）代表盤中曾經到過、但沒守住的價格。",
            "長上影線：盤中衝高但被賣回來，上方有賣壓。長下影線：盤中殺低但被買回來，下方有支撐。")
    _lesson("均線（MA）", "過去 N 天收盤價的平均。MA5 ≈ 一週、MA20 ≈ 一個月、MA60 ≈ 一季。"
            "股價站在均線上、短均線在長均線上（多頭排列），代表買的人願意用更高價買。",
            "MA5 > MA20 > MA60 且收盤在 MA20 之上，就是系統的「均線多頭」條件。")
    _lesson("成交量與換手率", "成交量是今天成交了多少股；換手率 = 成交量 ÷ 流通股數，代表今天有多少比例的股票換手。"
            "突破時放量，代表有真的資金在買，不是少數人拉抬。",
            "換手率 < 3% 偏冷、3–5% 正常、5–10% 活絡、> 10% 過熱（要小心追高）。")
    _lesson("突破", "股價收盤超過近 20 日最高點，代表過去一個月想賣的人都被吃掉了，上方壓力變小。"
            "系統要求同時放量（量 > 50 日均量 1.5 倍），避免假突破。")
    _lesson("停損與 R 倍數", "停損是「判斷錯了」的價格。1R = 進場價 − 停損價，也就是這筆最多賠的每股金額。"
            "之後所有損益都用 R 衡量，才能比較不同價位的股票。",
            "進場 100、停損 95，1R = 5 元。漲到 110 是 +2R；跌到 95 停損是 −1R。")
    _lesson("本益比（PE）", "股價 ÷ 每股盈餘。代表用現在的獲利，要幾年才賺回股價。"
            "低本益比可能是便宜，也可能是市場預期獲利會衰退；高本益比代表市場期待高成長。")
    _lesson("股價淨值比（PB）", "股價 ÷ 每股淨值。淨值是公司資產扣掉負債後屬於股東的部分。"
            "PB < 1 代表股價低於帳面價值；高獲利公司的 PB 通常遠高於 1。")
    _lesson("台股交易規則", "1 張 = 1,000 股；漲跌幅限制 10%；成交後第 2 個營業日交割（T+2）。"
            "成本：手續費 0.1425%（買賣各一次，多數券商有折扣，最低 20 元）、證交稅 0.3%（賣出時，ETF 0.1%）。"
            "一買一賣不打折的成本約 0.585%。")

    st.markdown("### 部位計算機：這筆該買幾張？")
    c1, c2, c3, c4 = st.columns(4)
    cap = c1.number_input("總資金", 100_000, 50_000_000, int(st.session_state.get("total_capital", 1_000_000)),
                          100_000, key="pos_cap")
    risk = c2.number_input("單筆風險 %", 0.25, 5.0, 1.0, 0.25, key="pos_risk") / 100
    entry = c3.number_input("進場價", 1.0, 10_000.0, 100.0, 0.5, key="pos_entry")
    stop = c4.number_input("停損價", 0.5, 10_000.0, 95.0, 0.5, key="pos_stop")
    if stop >= entry:
        st.markdown("停損價要低於進場價。")
    else:
        shares = int(cap * risk / (entry - stop))
        lots = shares // 1000
        st.markdown(f"每股風險 {entry - stop:,.2f} 元，最多賠 {fmt_money(cap * risk)} → 最多 **{shares:,} 股**"
                    f"（**{lots} 張**{'，零股 ' + format(shares % 1000, ',') + ' 股' if shares % 1000 else ''}），"
                    f"需資金約 {fmt_money(lots * 1000 * entry)}。")


