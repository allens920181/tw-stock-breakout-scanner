def _philosophy():
    st.markdown("## 交易哲學：這套系統相信什麼")
    st.caption("先讀這一頁。後面所有規則（停損、時間停損、月虧損上限、空頭休息）都是從這些信念推出來的。")
    _lesson("1. 風險先於報酬",
            "每一筆交易下單前，先決定「錯了最多賠多少」，再決定買多少。報酬是市場給的，風險是你自己控制的。",
            "總資金 100 萬、單筆風險 1%：這筆最多賠 1 萬。進場 100 元、停損 95 元，每股風險 5 元，"
            "所以最多買 2,000 股（2 張）。")
    _lesson("2. 流程勝過預測",
            "沒有人能穩定預測明天漲跌。能重複的是流程：同樣的條件進場、同樣的規則出場、同樣的部位大小。"
            "單筆結果是運氣，一百筆的平均才是能力。",
            "一個勝率 40%、贏的時候平均賺 2.2R 的系統，期望值是 0.4×2.2 − 0.6×1 = +0.28R。"
            "它會有很多次連續虧損，但照做一百次，平均每次賺 0.28 倍風險。")
    _lesson("3. 承認不確定",
            "回測會高估、樣本少會騙人。所以系統會標出樣本數與信賴區間，並把「樣本外」結果放在最前面。"
            "看到「樣本不足」時，就把數字當參考，不要當保證。")
    _lesson("4. 複利來自不爆倉，不是押對一次",
            "虧 50% 要賺 100% 才回得來。小虧、小賺、持續做，比一次大賺更能長期累積。"
            "這也是為什麼空頭時休息、本月虧到上限就停手。",
            "虧 10% → 要賺 11% 回本；虧 30% → 要賺 43%；虧 50% → 要賺 100%。")
    _lesson("5. 目標是結果，不是手段",
            "「每月賺一萬」是用來推算要做幾筆、該用多少資金，不能拿來推高風險。"
            "月底還沒達標就加碼、放寬停損，是散戶最常見的爆倉路徑。")

    _lesson("6. 用證據檢查自己的方法",
            "2026 年 11 月用 1,034 檔上市股、兩年資料做的實證：系統的突破訊號、相對強度挑股，都沒有比「在同樣條件下隨機挑股」更好。"
            "前 15 個月連隨機挑都賺，最近 6 個月沒有任何一種方法有顯著獲利。代表賺錢的關鍵是大盤環境與風險控制，不是挑中哪一檔。"
            "詳見「策略驗證 → 大樣本實證」。")

    st.markdown("### 你的月目標，用數字算一次")
    c1, c2, c3 = st.columns(3)
    cap = c1.number_input("總資金（元）", 100_000, 50_000_000, int(st.session_state.get("total_capital", 1_000_000)),
                          100_000, key="learn_cap")
    risk = c2.number_input("單筆風險 %", 0.25, 5.0, float(st.session_state.get("risk_pct", 1.0)), 0.25,
                           key="learn_risk") / 100
    target = c3.number_input("月目標（元）", 1_000, 1_000_000, int(st.session_state.get("month_target", 10_000)),
                             1_000, key="learn_target")
    d1, d2 = st.columns(2)
    win = d1.slider("勝率 %", 20, 70, 40, key="learn_win") / 100
    aw = d2.slider("贏的時候平均賺幾 R", 1.0, 4.0, 2.2, 0.1, key="learn_aw")
    e = win * aw - (1 - win)
    need = trades_needed(target, cap, risk, e)
    if need is None:
        st.markdown(f"**期望值 {e:+.2f}R：這組數字長期是賠錢的**，再多交易也達不到目標。先提高勝率或賺賠比。")
    else:
        sim = simulate_months(win, aw, need, cap * risk, target)
        st.markdown(
            f"- 每筆最多賠 **{fmt_money(cap * risk)}**，期望值 **{e:+.2f}R**，平均每月要做 **{need:.1f} 筆**。\n"
            f"- 模擬一萬個月（每月 {sim['trades']} 筆）：平均每月 {fmt_money(sim['mean'], signed=True)}，"
            f"**{sim['p_loss'] * 100:.0f}% 的月份會虧損**、{sim['p_hit'] * 100:.0f}% 的月份達標。\n"
            f"- 最差的 10% 月份會在 {fmt_money(sim['p10'], signed=True)} 以下。這就是為什麼要用三個月平均看目標。")


