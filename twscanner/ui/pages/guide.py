"""📖 操作教學分頁（靜態說明）。"""

import streamlit as st


def render():
    """📖 操作教學"""
    st.markdown("## 📖 系統操作教學")
    st.caption("從挑標的 → 定價格 → 管理賣出的完整流程。所有名詞可點欄位旁的 (?) 看說明。")

    st.info("**一句話流程**：大盤綠燈 → 掃描挑「進場＋法人買超＋RS強＋沒追高＋沒臨財報」"
            "→ 照卡片的進場/停損/目標/張數下單 → 持股管理每天看賣出建議 → 嚴守停損。")

    with st.expander("⓪ 先選「策略模式」（側欄最上方）", expanded=True):
        st.markdown(
            "| 模式 | 抓什麼 | 適合 |\n"
            "|---|---|---|\n"
            "| **強勢突破** | 已突破創高＋量增＋法人買 | 追動能、買強勢（會買在已漲一段）|\n"
            "| **早期突破** | 只抓「剛突破、沒追高」 | 想參與突破但不想追高 |\n"
            "| **潛伏起漲前** | 窄幅整理＋量縮＋站穩均線＋接近未突破＋法人吸籌 | 想埋伏在發動前 |\n\n"
            "潛伏模式的進場建議顯示為「**埋伏 · 潛伏**」，是買在整理區、停損放箱底，等突破。\n"
            "三種模式的籌碼否決、部位管理、綜合評級都共用同一套。"
        )

    with st.expander("① 買之前先看「大盤」（紅燈別買）", expanded=True):
        st.markdown(
            "畫面最上方的 **大盤狀態**：\n\n"
            "- 🟢 **多頭** → 正常操作\n"
            "- 🟡 **中性** → 部位自動減半\n"
            "- 🔴 **空頭** → 整套停手，系統會自動把進場降級\n\n"
            "另有 **美股風險偏好**（VIX＋SPX）與台股取較保守者，一起影響建議張數。"
        )

    with st.expander("② 挑買入標的（買入掃描分頁）", expanded=True):
        st.markdown(
            "跑完掃描後，看候選卡片。一檔好買點要同時滿足：\n\n"
            "| 看哪一欄 | 理想狀態 | 意義 |\n"
            "|---|---|---|\n"
            "| **操作建議** | 進場 · 突破/拉回 | 系統判定可進場 |\n"
            "| **評分顯示** | 越高越好（如 ≥7/10） | 多條件同時成立 |\n"
            "| **籌碼確認** | 法人買超 / 法人連買N日 | 有大戶在買 |\n"
            "| **相對強度RS%** | 正值、越大越好 | 比大盤強 |\n"
            "| **族群同步** | 同步 2 檔以上 | 整族群在動有撐 |\n"
            "| **現價偏離%** | 接近 0（別超過 +3~5%） | 沒追高 |\n\n"
            "**出現這些要跳過 / 小心**（系統會自動降級或警示）：\n"
            "- ⚠ 籌碼確認 = **法人賣超** → 突破恐是出貨\n"
            "- ⚠ 融資券提示 = **融資爆增** → 散戶過熱反指標\n"
            "- ⚠ **距財報日** 很近（前 3 日內）→ 避開財報波動\n"
            "- ⚠ **部位提示** 有「追高 / 乖離過熱」→ 等回檔"
        )

    with st.expander("③ 價格怎麼定（卡片已算好，照抄）", expanded=True):
        st.markdown(
            "| 欄位 | 怎麼用 |\n"
            "|---|---|\n"
            "| **進場參考價** | 你的買入掛單價 |\n"
            "| **停損價** | 跌破就無條件賣出（ATR 抓好風險距離）|\n"
            "| **目標價1(+1R半倉)** | 到這裡先賣一半鎖利 |\n"
            "| **目標價2(+2R出清)** | 到這裡全部出清 |\n"
            "| **建議張數** | 固定風險法算好（含資金上限、族群降碼）|\n\n"
            "🔑 **紀律**：進場前先把停損價設好，停損是唯一不能凹的。"
        )

    with st.expander("④ 賣出管理（持股管理分頁）", expanded=True):
        st.markdown(
            "把持股填進去（代號、成本價、進場日、股數），系統每天看 **操作建議** 欄：\n\n"
            "| 系統建議 | 你做什麼 |\n"
            "|---|---|\n"
            "| ⛔ 停損出清 | 全部賣（跌破停損）|\n"
            "| 🔴 技術轉弱 | 全部賣（KD 死叉＋跌破 MA20）|\n"
            "| 🟢 達 +1R 半倉鎖利 | 賣一半 |\n"
            "| 🟢 達 +2R 出清 | 全部賣 |\n"
            "| 🟡 移動停利(ATR) | 全部賣（獲利後跌破移動停利線）|\n"
            "| ⌛ 時間停損 | 全部賣（抱太久沒漲）|\n"
            "| ✅ 續抱 | 留著，每天再看 |\n\n"
            "賣出價參考同列的 **停損價 / 目標1 / 目標2 / 移動停利(ATR)**。"
        )

    with st.expander("⑤ ⚠ 最重要：先驗證策略有沒有效（回測分頁）", expanded=True):
        st.markdown(
            "**別拿沒驗證的設定下單。** 在回測分頁：\n\n"
            "1. 跑回測 → 只看 **🎯 OOS 期望值R（樣本外）**，要 **> 0 且 CI 不跨 0** 才算有 edge\n"
            "2. 看 **Regime 拆解** → 確認不是只在多頭賺\n"
            "3. 跑 **因子驗證 / 參數高原圖** → 砍掉沒貢獻的因子、參數取穩健中點\n\n"
            "→ 報酬已內扣台股來回交易成本（手續費＋證交稅約 0.45~0.6%），數字才可信。"
        )

    st.markdown("---")
    st.markdown("### 📊 進階：怎麼讀表格、怎麼分析持股")

    with st.expander("Ⓐ 各模式「該看哪個指標」（重要）", expanded=False):
        st.markdown(
            "不同策略模式，看的主指標不一樣，別看錯：\n\n"
            "| 模式 | **主看** | RS 角色 |\n"
            "|---|---|---|\n"
            "| **潛伏起漲前** | **啟動就緒度 ⚡** ＋ 是否「進場·突破確認」＋ 籌碼吸籌 | 配角（潛伏抓落後股，RS 多半負是正常）|\n"
            "| **早期 / 強勢突破** | **綜合評級 ＋ RS** ＋ 籌碼 | **主角（要正、越高越好）** |\n\n"
            "**潛伏模式判讀順序**：啟動就緒度(⚡已啟動/即將啟動≥70) → 操作建議是「進場·突破確認」(可買) 還是「觀察·待突破」(還沒發動) → 籌碼確認(法人連買) → 最後參考 RS。\n\n"
            "**突破模式判讀順序**：綜合評級(A/B) → RS 正且高 → 籌碼確認 → 營收動能(年增=有基本面背書) → 沒紅旗(法人賣超/融資爆增/財報臨近/營收大減)。"
        )

    with st.expander("Ⓑ RS 相對強度怎麼看", expanded=False):
        st.markdown(
            "**RS% = 個股 60 日報酬 − 大盤 60 日報酬**，衡量「比大盤強還弱」。\n\n"
            "- **RS > 0**：贏大盤＝領漲股，啟動成功率/續航力較高 ← 突破模式優先\n"
            "- **RS ≈ 0**：跟大盤同步\n"
            "- **RS 負很多（如 −30）**：落後股，補漲性質 → **到目標就走、別當主流飆股抱**\n\n"
            "RS 負不代表不能買（潛伏/補漲就是賭這個），但要知道「它本來是弱的」。"
        )

    with st.expander("Ⓒ 怎麼自己分析一檔持股（買進後）", expanded=False):
        st.markdown(
            "拿到一檔持股，依序檢查（也可丟「持股管理」分頁自動跑）：\n\n"
            "**1. 算損益與 R 倍數**\n"
            "- 損益% =（現價 − 你的成本）/ 成本\n"
            "- R 倍數 =（現價 − 成本）/（成本 − 停損）。**達 +1R 賣半、+2R 出清**\n\n"
            "**2. 看位置（買貴了沒）**\n"
            "- 收盤乖離 MA20 太多（如 >8%）＝買在追高尾段，停損要收緊\n"
            "- 距 20 日高：負(已突破)、正(還沒突破)\n\n"
            "**3. 看籌碼動向（撐不撐得住）**\n"
            "- 法人連買天數、外資是否同步買 → 持續吸籌＝有撐；轉賣超＝警訊\n\n"
            "**4. 設好停損與目標**\n"
            "- 停損：系統停損價，或更緊的 進場−1.5×ATR\n"
            "- 目標：目標價1(先賣半) / 目標價2(出清)\n\n"
            "**5. 看 RS 決定抱多久**\n"
            "- RS 弱(落後股)：到目標就走，別期待大波段\n"
            "- RS 強(領漲股)：可用移動停利(ATR)續抱波段\n\n"
            "**範例**：買 34.3、現 35.85、停損 33.55 → R =（35.85−34.3）/（34.3−33.55）≈ **+2R**，"
            "已達標 → 先賣半鎖利、停損移到成本價保本。"
        )

    st.divider()
    st.caption("⚠ 本工具為技術＋籌碼面決策輔助，非投資建議。籌碼/融資/財報為當日 best-effort 資料，"
               "最終下單與風險自負。系統僅涵蓋上市股，不含上櫃。")
